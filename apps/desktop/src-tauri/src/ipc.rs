//! IPC surface: every command and event the webview can use.
//!
//! Types are exported to `apps/desktop/src/lib/ipc/bindings.ts` by tauri-specta.
//! Never edit that file by hand; run `pnpm bindings`.

// Tauri extracts command arguments (e.g. `AppHandle`) by value.
#![allow(clippy::needless_pass_by_value)]

mod accounts;
mod app;
mod doctor;
mod events;
mod quick_share;
mod routes;
mod settings;

use std::path::PathBuf;

use specta_typescript::Typescript;
use tauri_specta::{Builder, ErrorHandlingMode, collect_commands, collect_events};

pub use events::{EntityChanged, EntityKind, MenuAction, MenuCommand};

const BINDINGS_HEADER: &str = "// Generated by tauri-specta from apps/desktop/src-tauri. Do not edit.\n// Regenerate with `pnpm bindings`.\n";

/// The specta builder holding every command and event.
pub(crate) fn builder() -> Builder<tauri::Wry> {
    Builder::<tauri::Wry>::new()
        .error_handling(ErrorHandlingMode::Throw)
        .commands(collect_commands![
            app::app_info,
            app::app_ready,
            app::app_accent_color,
            app::app_report_error,
            app::app_open_settings,
            app::app_quit,
            app::app_open_at_login,
            app::app_set_open_at_login,
            settings::settings_get,
            settings::settings_set,
            quick_share::binary_status,
            quick_share::binary_install,
            quick_share::binary_check_update,
            quick_share::binary_reveal,
            quick_share::services_list,
            quick_share::quick_share_start,
            quick_share::quick_share_stop,
            quick_share::quick_share_list,
            quick_share::quick_share_stats,
            quick_share::quick_share_logs,
            quick_share::quick_share_qr,
            accounts::accounts_list,
            accounts::accounts_add_token,
            accounts::accounts_open_token_page,
            accounts::accounts_detect_cert,
            accounts::accounts_import_cert,
            accounts::accounts_remove,
            accounts::accounts_capabilities,
            accounts::domains_list,
            accounts::accounts_oauth_available,
            accounts::accounts_oauth_sign_in,
            accounts::accounts_oauth_cancel,
            routes::routes_overview,
            routes::routes_preview,
            routes::routes_apply,
            routes::routes_verify,
            routes::routes_drift,
            routes::routes_keep_theirs,
            routes::routes_activity,
            routes::tunnels_list,
            routes::tunnels_start,
            routes::tunnels_stop,
            routes::tunnels_clean,
            routes::import_scan,
            routes::foreign_list,
            routes::foreign_stop,
            routes::tunnels_logs,
            routes::tunnels_traffic,
            routes::tunnels_traffic_history,
            routes::tunnels_always_on,
            routes::tunnels_set_always_on,
            doctor::doctor_run,
            doctor::doctor_fix_safe,
            doctor::diagnostics_preview,
            doctor::diagnostics_export
        ])
        .events(collect_events![EntityChanged, MenuAction])
}

/// Path of the generated TypeScript bindings.
fn bindings_path() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../src/lib/ipc/bindings.ts")
}

/// Writes the TypeScript bindings and returns the path written.
///
/// # Errors
/// Returns an error if the types can't be exported or the file can't be written.
pub fn export_bindings() -> Result<PathBuf, Box<dyn std::error::Error>> {
    let path = bindings_path();
    builder().export(Typescript::default().header(BINDINGS_HEADER), &path)?;
    Ok(path)
}
